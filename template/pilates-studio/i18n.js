// 1.5 → «1½», 12 → «12+»
function fmtAge(a) {
  if (a >= 12) return '12+'
  return a % 1 ? `${Math.floor(a)}½` : String(a)
}

function list(items, and) {
  if (items.length < 2) return items.join('')
  return `${items.slice(0, -1).join(', ')} ${and} ${items.at(-1)}`
}

